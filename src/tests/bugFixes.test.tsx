describe("the customer ID number is never invented", () => {
  const fields = getFieldsForStateAndVersion("CA", "10");

  it("blocks generation when DAQ is empty, even with auto-generation on", () => {
    // `autoGenerateDiscriminator` swept up every jurisdiction generator, which
    // included DAQ. An empty licence number therefore produced a barcode
    // carrying a random one instead of the missing-mandatory-field error, and
    // the value never appeared in the form the user was looking at.
    const data = formFor("CA");
    delete data.DAQ;

    expect(() =>
      generateAAMVAPayload("CA", "10", fields, data, {
        strictMode: true,
        autoGenerateDiscriminator: true
      })
    ).toThrow(/Missing mandatory fields.*Customer ID Number \(DAQ\)/s);
  });

  it("still auto-generates the document discriminator", () => {
    const data = formFor("CA");
    delete data.DCF;

    const payload = generateAAMVAPayload("CA", "10", fields, data, {
      strictMode: true,
      autoGenerateDiscriminator: true
    });

    expect(decodeAAMVA(payload).json?.DCF).toBeTruthy();
  });

  it("does not inject codes the selected version has no field for", () => {
    // v01 has no DCF or DDB. They were written into the caller's object anyway.
    const v01Fields = getFieldsForStateAndVersion("VA", "01");
    const data: Record<string, string> = {
      DAA: "DOE,JANE,Q",
      DAG: "123 SAMPLE ST",
      DAI: "RICHMOND",
      DAJ: "VA",
      DAK: "23219",
      DAQ: "D12345678",
      DBA: "20290101",
      DBB: "19900215",
      DBC: "F"
    };

    const payload = generateAAMVAPayload("VA", "01", v01Fields, data, {
      autoGenerateDiscriminator: true
    });

    expect(payload).not.toContain("DCF");
    expect(payload).not.toContain("DDB");
  });
});

describe("generateAAMVAPayload does not mutate its input", () => {
  it("leaves the caller's object exactly as it was passed", () => {
    const fields = getFieldsForStateAndVersion("CA", "10");
    const data = formFor("CA", { DAG: "123 sample st", DCS: "  doe  " });
    delete data.DCF;
    const before = JSON.stringify(data);

    generateAAMVAPayload("CA", "10", fields, data, {
      strictMode: false,
      autoGenerateDiscriminator: true
    });

    // Normalisation (uppercasing, trimming) and auto-fill both used to be
    // written straight back into the caller's object.
    expect(JSON.stringify(data)).toBe(before);
  });
});

describe("AAMVA version coverage", () => {
  it("defines every version from 01 to 10", () => {
    for (let i = 1; i <= 10; i++) {
      const key = String(i).padStart(2, "0");
      expect(isSupportedVersion(key), `version ${key}`).toBe(true);
    }
  });

  it("lists versions in ascending order for the pickers", () => {
    // Object.keys puts the integer-like "10" ahead of "01".."09", so every
    // dropdown built from it opened on version 10.
    expect(AAMVA_VERSION_KEYS).toEqual([
      "01",
      "02",
      "03",
      "04",
      "05",
      "06",
      "07",
      "08",
      "09",
      "10"
    ]);
    expect([...AAMVA_VERSION_KEYS].sort()).toEqual([...AAMVA_VERSION_KEYS]);
    expect(AAMVA_VERSION_KEYS.length).toBe(Object.keys(AAMVA_VERSIONS).length);
  });

  it("builds a usable form and payload for 05, 06 and 07", () => {
    for (const version of ["05", "06", "07"]) {
      const fields = getFieldsForStateAndVersion("CA", version);
      expect(fields.length, `v${version} field count`).toBeGreaterThan(0);
      const payload = generateAAMVAPayload("CA", version, fields, formFor("CA"), {
        strictMode: false
      });
      expect(decodeAAMVA(payload).json?.version).toBe(version);
    }
  });

  it("rejects a version outside the table", () => {
    expect(isSupportedVersion("99")).toBe(false);
    expect(isSupportedVersion("")).toBe(false);
  });
});

describe("getMandatoryFields honours the jurisdiction", () => {
  it("returns exactly the required fields the form renders", () => {
    // It ignored `stateCode` entirely and read the version table directly. That
    // only agreed with the form by accident of the exclusion filter.
    for (const state of ["NY", "CT", "CA", "PR"]) {
      for (const version of AAMVA_VERSION_KEYS) {
        const shown = getFieldsForStateAndVersion(state, version).filter((f) => f.required);
        expect(getMandatoryFields(state, version), `${state} v${version}`).toEqual(shown);
      }
    }
  });
});

describe("strict mode blocks jurisdiction advisories", () => {
  const fields = getFieldsForStateAndVersion("TN", "09");
  // TN's rule pack wants 7-9 digits; this is neither, so it is a warning.
  const offending = formFor("TN", { DAQ: "ZZZZZZZZZ", DCF: "1234567890", DAI: "NASHVILLE" });

  it("surfaces the advisory in the validation report", () => {
    const issue = getValidationIssues(fields, offending, "TN", false).find((i) => i.code === "DAQ");
    expect(issue?.severity).toBe("warning");
  });

  it("refuses to generate under strict mode", () => {
    // Strict mode is documented as treating warnings as errors, and cross-field
    // warnings did block — but per-field rule packs were never consulted at
    // generation time, so the payload was built anyway.
    expect(() => generateAAMVAPayload("TN", "09", fields, offending, { strictMode: true })).toThrow(
      /jurisdiction advisories/i
    );
  });

  it("still generates with strict mode off", () => {
    expect(() =>
      generateAAMVAPayload("TN", "09", fields, offending, { strictMode: false })
    ).not.toThrow();
  });

  it("promotes the advisory to an error in the report under strict mode", () => {
    const issue = getValidationIssues(fields, offending, "TN", true).find((i) => i.code === "DAQ");
    expect(issue?.severity).toBe("error");
  });
});

describe("evaluateFieldValue weighs every rule-pack constraint", () => {
  const field: AAMVAField = { code: "DAQ", label: "Customer ID Number", type: "string" };

  it("reports an error constraint even when a warning precedes it", () => {
    // The loop returned on the first failing constraint, so a warning listed
    // ahead of an error masked the error and reported ok: true.
    const original = JURISDICTION_RULE_PACKS.WY;
    (JURISDICTION_RULE_PACKS as Record<string, unknown>).WY = {
      state: "WY",
      constraints: [
        { field: "DAQ", pattern: /^[0-9]+$/, message: "advisory", severity: "warning" },
        { field: "DAQ", pattern: /^.{9,10}$/, message: "hard length rule", severity: "error" }
      ]
    };

    try {
      const result = evaluateFieldValue(field, "AB", "WY");
      expect(result.ok).toBe(false);
      expect(result.severity).toBe("error");
      expect(result.message).toBe("hard length rule");
    } finally {
      (JURISDICTION_RULE_PACKS as Record<string, unknown>).WY = original;
    }
  });
});

describe("decodePayload rejects things that are not field maps", () => {
  it("refuses a JSON array", () => {
    // Arrays are typeof "object", so one came back as a field map whose keys
    // were array indices — and the scanner loaded it straight into the form.
    expect(decodePayload("[1,2,3]").error).toBeTruthy();
    expect(decodePayload("[1,2,3]").data).toBeUndefined();
    expect(decodeAAMVA("[1,2,3]").ok).toBeUndefined();
  });

  it("still accepts a plain object", () => {
    expect(decodePayload('{"DCS":"DOE"}').data).toEqual({ DCS: "DOE" });
  });
});

